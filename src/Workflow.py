def has_decoys(fasta_path, prefix='DECOY_'):
    """True if any FASTA header carries the decoy accession prefix."""
    with open(fasta_path, 'r', errors='replace') as f:
        for line in f:
            if line.startswith('>') and prefix in line[1:].split(maxsplit=1)[0]:
                return True
    return False


